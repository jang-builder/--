  // items: [{ label:'상품명', text:'...', official:true }]  official 필드는 검사에서 제외
  function scan(items) {
    const found = [];
    (items || []).forEach(item => {
      if (!item || !item.text || item.official) return;
      const raw = String(item.text);
      RULES.forEach(rule => {
        // 예외로 둔 표현(GMP 인증 등)은 지운 뒤에 검사한다
        let text = raw;
        if (rule.skip) rule.skip.forEach(re => { text = text.replace(re, ' '); });
        rule.words.forEach(w => {
          if (text.indexOf(w) === -1) return;
          found.push({ level: rule.level, word: w, where: item.label, why: rule.why, fix: rule.fix });
        });
      });
    });
    // 같은 단어가 여러 곳에 있으면 한 줄로 합친다
    const merged = {};
    found.forEach(f => {
      const key = f.level + '|' + f.word;
      if (merged[key]) { if (merged[key].where.indexOf(f.where) === -1) merged[key].where += ', ' + f.where; }
      else merged[key] = Object.assign({}, f);
    });
    const list = Object.values(merged);
    return {
      list,
      ban: list.filter(f => f.level === 'ban').length,
      warn: list.filter(f => f.level === 'warn').length
    };
  }

